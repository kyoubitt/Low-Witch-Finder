#!/usr/bin/env python3
"""gen_trees.py TREEDIR OUT.h - turns the dumps from dump_trees.py into engine/tools/lysh/src/biome_trees.h: every distinct biome search tree
the game has had, node for node (the game's own tree, so ties break as the game breaks them), and a table saying which versions use which.
A node is: 6 parameter ranges (temperature, humidity, continentalness, erosion, depth, weirdness), how many children, the biome id (leaf),
and where its subtree ends. Depth first: a node's first child is the next node. Biome ids are the cubiomes numbers the rest of the app uses."""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.realpath(__file__)), "..", ".."))
import witchhut_common as W  # noqa: E402

treedir, outpath = sys.argv[1], sys.argv[2]
groups = json.load(open(os.path.join(treedir, "groups.json")))
ids = {W.biome_name(i).replace(" ", "_"): i for i in W._B}


def vkey(v):
    return [int(x) if x.isdigit() else 0 for x in v.split(".")]


def load(version):
    rows = []
    for line in open(os.path.join(treedir, "tree_%s.txt" % version)):
        t = line.split()
        nums = list(map(int, t[2:]))
        assert nums[12:] == [0, 0], "this tree has an offset; the C walker ignores it"
        assert all(-32768 <= n <= 32767 for n in nums[:12])
        rows.append((t[0], int(t[1]) if t[0] == "I" else ids[t[1]], nums[:12]))
    end = [0] * len(rows)

    def close(i):
        k = i + 1
        if rows[i][0] == "I":
            for _ in range(rows[i][1]):
                k = close(k)
        end[i] = k
        return k
    assert close(0) == len(rows)
    return rows, end


sys.setrecursionlimit(10000)
trees = sorted(groups.values(), key=lambda vs: vkey(sorted(vs, key=vkey)[0]))
out = ["/* GENERATED by tools/accuracy/gen_trees.py from the game's own trees (tools/accuracy/dump_trees.py) -- do not edit.\n"
       " * Every distinct overworld biome search tree Minecraft has had since 1.18, node for node. */\n#include <stdint.h>\n"]
table = []
for n, vs in enumerate(trees):
    vs = sorted(vs, key=vkey)
    rows, end = load(vs[0])
    out.append("/* tree %d: %s */" % (n, ", ".join(vs)))
    out.append("static const int16_t gtree%d_range[][12] = {" % n)
    out += ["    {%s}," % ",".join(map(str, r[2])) for r in rows]
    out.append("};")
    out.append("static const uint8_t gtree%d_kids[] = {%s};" % (n, ",".join(str(r[1] if r[0] == "I" else 0) for r in rows)))
    out.append("static const uint8_t gtree%d_biome[] = {%s};" % (n, ",".join(str(r[1] if r[0] == "L" else 0) for r in rows)))
    out.append("static const uint16_t gtree%d_end[] = {%s};\n" % (n, ",".join(map(str, end))))
    for v in vs:
        table.append((v, n))
table.sort(key=lambda x: vkey(x[0]))
out.append("#define LYSH_TREE_COUNT %d" % len(trees))
out.append("/* name, tree, is 1.18.x, is before 26.2 */")
out.append("static const struct { const char *name; int tree, is_118, pre_262; } lysh_versions[] = {")
for v, n in table:
    out.append('    {"%s", %d, %d, %d},' % (v, n, 1 if v.startswith("1.18") else 0, 1 if vkey(v) < [26, 2] else 0))
out.append("};")
out.append("#define LYSH_TREE_REFS { " + ", ".join("{gtree%d_range, gtree%d_kids, gtree%d_biome, gtree%d_end}" % ((n,) * 4) for n in range(len(trees))) + " }")
open(outpath, "w").write("\n".join(out) + "\n")
print(len(trees), "trees,", len(table), "versions ->", outpath)
